    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
String placa = jTextField1.getText(); 
String servico = jTextField2.getText();

try {
    // Liga ao banco de dados oficinapro
    java.sql.Connection conexao = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/oficinapro", "root", "6666");
    
    // Prepara e executa a inserção
    String sql = "INSERT INTO ordem_servico (placa, servico) VALUES (?, ?)";
    java.sql.PreparedStatement st = conexao.prepareStatement(sql);
    st.setString(1, placa);
    st.setString(2, servico);
    
    st.executeUpdate();
    
    javax.swing.JOptionPane.showMessageDialog(this, "Serviço gravado com sucesso no MySQL!");
    
    // Limpa os campos
    jTextField1.setText("");
    jTextField2.setText("");
    
    conexao.close();

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Erro de ligação: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

